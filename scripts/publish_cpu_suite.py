"""Train both portable CPU backends on every prepared dataset and publish the comparison.

Writes reports/cpu-suite.json, reports/cpu-suite.md and docs/risk-coverage.svg.
Prepare the data first (scripts/prepare_*.py). Models go to a temporary registry;
the repository registry and active pointer are not touched.
"""

import argparse
import dataclasses
import json
import statistics
import tempfile
import time
from pathlib import Path

from localdesk.analysis import out_of_scope
from localdesk.config import Experiment
from localdesk.core import decide
from localdesk.dataset import prepare
from localdesk.pipeline import run_experiment
from localdesk.registry import Registry

DATASETS = {
    "it-support": "IT Support Tickets",
    "sms-filter": "UCI SMS Spam",
    "banking77": "Banking77",
    "clinc150": "CLINC150",
}
BACKENDS = {
    "baseline": {"backend": "baseline", "C": 4.0, "max_iter": 2000},
    "tfidf": {"backend": "tfidf", "C": 4.0, "max_features": 40000},
}
STYLE = {"baseline": ("#E69F00", "6 4"), "tfidf": ("#0072B2", "")}


def latency_ms(backend, texts):
    for text in texts[:20]:
        decide(text, backend)
    samples = []
    for text in texts:
        started = time.perf_counter()
        decide(text, backend)
        samples.append((time.perf_counter() - started) * 1000)
    return statistics.median(samples)


def run(name, kind, registry):
    experiment = Experiment.load(Path("experiments") / f"{name}.json")
    experiment = dataclasses.replace(experiment, training=BACKENDS[kind], registry=registry)
    result = run_experiment(experiment, run_id=f"{name}-{kind}")
    report = result["report"]
    backend, _ = Registry(registry).load(result["run_id"], require_qualified=False)
    test = prepare(experiment).rows["test"]
    entry = {
        "backend": kind,
        "split_counts": report["split_counts"],
        "accuracy": report["classification"]["accuracy"],
        "macro_f1": report["classification"]["macro_f1"],
        "ece": report["classification"]["ece"],
        "coverage": report["coverage"],
        "accepted_accuracy": report["accepted_accuracy"],
        "risk_coverage": report["risk_coverage"],
        "qualified": result["manifest"]["quality"]["qualified"],
        "temperature": report["training"]["temperature"],
        "train_seconds": report["runtime_seconds"],
        "model_bytes": (registry / result["run_id"] / "model.json.gz").stat().st_size,
        "median_latency_ms": latency_ms(backend, [row["state"] for row in test[:300]]),
    }
    ood = Path("data") / name / "ood.jsonl"
    if ood.is_file():
        texts = [json.loads(line)["text"] for line in ood.read_text("utf-8").splitlines()]
        in_scope = [
            max(decide(row["state"], backend)["probabilities"]["category"].values()) for row in test
        ]
        entry["out_of_scope"] = out_of_scope(texts, in_scope, backend)
    return entry


def pct(value):
    return "—" if value is None else f"{value * 100:.1f}%"


def ordered(results):
    return {name: results[name] for name in DATASETS if name in results}


def markdown(results):
    results = ordered(results)
    lines = [
        "# CPU backends on four public datasets",
        "",
        "Generated by `scripts/publish_cpu_suite.py`. Same pipeline and splits for both",
        "backends; C=4 for both (selected on tuning data in the earlier benchmark, not on test).",
        "Coverage is the share routed automatically under each task's fixed policy.",
        "",
        "| Dataset | Labels | Backend | Accuracy | Macro F1 | ECE | Auto-routed "
        "| Accuracy when routed | Coverage at 95% accuracy | AURC | Model | p50 latency |",
        "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, entries in results.items():
        for entry in entries:
            labels = entry["labels"]
            lines.append(
                f"| {DATASETS[name]} | {labels} | {entry['backend']} | {pct(entry['accuracy'])} "
                f"| {pct(entry['macro_f1'])} | {pct(entry['ece'])} | {pct(entry['coverage'])} "
                f"| {pct(entry['accepted_accuracy'])} "
                f"| {pct(entry['risk_coverage']['coverage_at_accuracy']['0.95'])} "
                f"| {entry['risk_coverage']['aurc']:.3f} | {entry['model_bytes'] / 1024:.0f} KiB "
                f"| {entry['median_latency_ms']:.2f} ms |"
            )
    ood = [entry for entries in results.values() for entry in entries if "out_of_scope" in entry]
    if ood:
        lines += [
            "",
            "## Out-of-scope queries (CLINC150)",
            "",
            "The 1,000 official out-of-scope test queries match none of the 150 intents and",
            "are never used for training or calibration.",
            "",
            "| Backend | Sent to review | Auto-routed (wrongly) | AUROC in vs out |",
            "| --- | ---: | ---: | ---: |",
        ]
        for entry in ood:
            analysis = entry["out_of_scope"]
            lines.append(
                f"| {entry['backend']} | {pct(analysis['sent_to_review'])} "
                f"| {pct(analysis['auto_routed'])} | {analysis['auroc_max_probability']:.3f} |"
            )
    lines += [
        "",
        "## Limits",
        "",
        "Single seed, public holdouts reused across methods; risk-coverage thresholds are",
        "read off the test set and are descriptive, not a calibrated operating policy.",
        "Latency is warmed, single-threaded, in-process `decide()` on this machine, not HTTP.",
        "",
    ]
    return "\n".join(lines)


def svg(results):
    """Small multiples: accuracy of the most confident share of predictions."""
    results = ordered(results)
    width, height, left, top, cell_w, cell_h = 960, 330, 64, 84, 178, 170
    gap = 56
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        'font-family="system-ui, -apple-system, Segoe UI, sans-serif" role="img" '
        'aria-labelledby="title desc">',
        '<title id="title">Accuracy versus share of requests handled automatically</title>',
        '<desc id="desc">For each dataset, accuracy of the most confident predictions as '
        "coverage grows, for the hashed baseline and the TF-IDF backend.</desc>",
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
        '<text x="20" y="26" font-size="16" font-weight="600" fill="#1f2328">'
        "Accuracy when the model handles only its most confident requests</text>",
    ]
    legend_x = 20
    for index, (kind, label) in enumerate(
        (("tfidf", "TF-IDF (new default)"), ("baseline", "hashed baseline"))
    ):
        color, dash = STYLE[kind]
        x = legend_x + index * 190
        parts.append(
            f'<line x1="{x}" y1="48" x2="{x + 24}" y2="48" stroke="{color}" '
            f'stroke-width="2.5" stroke-dasharray="{dash}"/>'
            f'<text x="{x + 30}" y="52" font-size="12" fill="#1f2328">{label}</text>'
        )
    for column, (name, entries) in enumerate(results.items()):
        x0 = left + column * (cell_w + gap)
        lows = [p["accuracy"] for e in entries for p in e["risk_coverage"]["points"]]
        floor = max(0.0, min(0.9, int(min(lows) * 10) / 10))

        def sx(value, x0=x0):
            return x0 + value * cell_w

        def sy(value, floor=floor):
            return top + (1 - (value - floor) / (1 - floor)) * cell_h

        parts.append(
            f'<text x="{x0}" y="{top - 12}" font-size="13" font-weight="600" '
            f'fill="#1f2328">{DATASETS[name]}</text>'
        )
        for tick in (floor, (floor + 1) / 2, 1.0):
            y = sy(tick)
            parts.append(
                f'<line x1="{x0}" y1="{y:.1f}" x2="{x0 + cell_w}" y2="{y:.1f}" '
                'stroke="#d0d7de" stroke-width="1"/>'
                f'<text x="{x0 - 6}" y="{y + 4:.1f}" font-size="11" fill="#59636e" '
                f'text-anchor="end">{tick * 100:.0f}%</text>'
            )
        for tick in (0.0, 0.5, 1.0):
            parts.append(
                f'<text x="{sx(tick):.1f}" y="{top + cell_h + 16}" font-size="11" '
                f'fill="#59636e" text-anchor="middle">{tick * 100:.0f}%</text>'
            )
        for entry in sorted(entries, key=lambda e: e["backend"] == "tfidf"):
            color, dash = STYLE[entry["backend"]]
            points = " ".join(
                f"{sx(p['coverage']):.1f},{sy(p['accuracy']):.1f}"
                for p in entry["risk_coverage"]["points"]
            )
            parts.append(
                f'<polyline points="{points}" fill="none" stroke="{color}" '
                f'stroke-width="2.5" stroke-dasharray="{dash}" stroke-linejoin="round"/>'
            )
    parts.append(
        f'<text x="{width / 2}" y="{height - 14}" font-size="12" fill="#59636e" '
        'text-anchor="middle">Share of requests routed automatically (most confident first)'
        "</text>"
    )
    parts.append(
        f'<text x="16" y="{top + cell_h / 2}" font-size="12" fill="#59636e" '
        f'text-anchor="middle" transform="rotate(-90 16 {top + cell_h / 2})">Accuracy</text>'
    )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=DATASETS)
    args = parser.parse_args()
    results = {}
    with tempfile.TemporaryDirectory() as directory:
        for name in args.datasets:
            labels = len(Experiment.load(Path("experiments") / f"{name}.json").task.labels)
            results[name] = []
            for kind in BACKENDS:
                entry = run(name, kind, Path(directory))
                entry["labels"] = labels
                results[name].append(entry)
                print(name, kind, pct(entry["accuracy"]), pct(entry["macro_f1"]), flush=True)
    Path("reports/cpu-suite.json").write_text(
        json.dumps(results, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    Path("reports/cpu-suite.md").write_text(markdown(results), encoding="utf-8")
    Path("docs/risk-coverage.svg").write_text(svg(results), encoding="utf-8")


if __name__ == "__main__":
    main()
